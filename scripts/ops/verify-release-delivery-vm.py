class GuestMeasurements:
    def __init__(self, *paths):
        self.paths = {p.stat().st_dev: p for p in paths}
        self.before = self.sample()
        self.minimum = self.before.copy()
        self.stop = threading.Event()
        self.thread = threading.Thread(target=self.monitor, daemon=True)

    def sample(self):
        fields = {}
        for line in Path("/proc/meminfo").read_text().splitlines():
            key, _, value = line.partition(":")
            if key in {"MemTotal", "MemAvailable", "SwapFree", "SwapTotal"}:
                fields[key] = int(value.split()[0]) * 1024
        for device, path in self.paths.items():
            fs = os.statvfs(path)
            fields[f"disk_available_dev_{device}_bytes"] = fs.f_bavail * fs.f_frsize
        return fields

    def monitor(self):
        while not self.stop.wait(1):
            for key, value in self.sample().items():
                self.minimum[key] = min(self.minimum[key], value)

    def finish(self):
        self.stop.set()
        self.thread.join()
        after = self.sample()
        return {"before": self.before, "minimum": {key: min(value, after[key])
                for key, value in self.minimum.items()}, "after": after, "sample_seconds": 1}


def verify_running(project, images):
    ids = docker("ps", "--all", "--quiet").splitlines()
    require(len(ids) == len(PERSISTENT), "UNEXPECTED_RUNTIME_SERVICE")
    observed = docker("container", "inspect", *ids)
    rows = json.loads(observed)
    services = set()
    for row in rows:
        labels = row["Config"]["Labels"]
        service = labels.get("com.docker.compose.service")
        require(labels.get("com.docker.compose.project") == project and service in PERSISTENT
                and service not in services, "UNEXPECTED_RUNTIME_SERVICE")
        state = row["State"]
        require(row["Image"] == images[service] and state["Running"] is True
                and state["Health"]["Status"] == "healthy" and row["RestartCount"] == 0
                and state["OOMKilled"] is False, "RUNNING_IMAGE_OR_HEALTH")
        if service == "api-server":
            env = dict(item.split("=", 1) for item in row["Config"]["Env"])
            require(all(env.get(key) == OFF[key] for key in
                        ("OWNER_BETA_ACCESS_MODE", "OWNER_BETA_PRICE_INPUT_MODE", "OWNER_BETA_PAPER_MODE",
                         "OWNER_BETA_PAPER_OFF_CONSENT_ENABLED", "OWNER_BETA_DAILY_MODE")),
                    "API_OFF_STATE")
        services.add(service)
        print(f"SERVICE: {service} image={row['Image']} health=healthy restarts=0", flush=True)
    require(services == set(PERSISTENT), "UNEXPECTED_RUNTIME_SERVICE")


