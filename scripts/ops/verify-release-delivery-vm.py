def upstream_override(data):
    # This fixed grammar is the importer-generated mapping. Reject any extra
    # Compose keys before ever passing the transferred configuration to Compose.
    require(data.startswith(UPSTREAM_HEADER), "UPSTREAM_OVERRIDE")
    data = data[len(UPSTREAM_HEADER):]
    require(data.startswith(b"services:\n") and data.endswith(b"\n"), "UPSTREAM_OVERRIDE")
    rows = re.findall(rb"  ([a-z-]+):\n    image: (" + IMAGE_ID.encode() + rb")\n", data)
    rendered = b"services:\n" + b"".join(b"  " + key + b":\n    image: " + value + b"\n"
                                          for key, value in rows)
    result = {key.decode(): value.decode() for key, value in rows}
    require(rendered == data and len(rows) == len(UPSTREAM) and set(result) == UPSTREAM
            and result["research-schema-check"] == result["postgres"], "UPSTREAM_OVERRIDE")
    return result


def inspect_image(reference, identity, revision=None):
    actual = docker("image", "inspect", "--format",
                    '{{.Id}}|{{.Os}}/{{.Architecture}}|{{index .Config.Labels "org.opencontainers.image.revision"}}',
                    reference).split("|")
    require(len(actual) == 3 and actual[:2] == [identity, "linux/amd64"],
            f"IMAGE_ID_OR_PLATFORM {reference}")
    require(revision is None or actual[2] == revision, f"IMAGE_REVISION {reference}")


def validate_inputs(import_dir, commit):
    simulation = release_helper("owner-beta-simulation-release")
    reader = simulation._daily()
    with reader.root_directory(import_dir) as directory:
        reader.directory_info(directory, uid=0, gid=0, mode=0o700)
    manifest = reader.read_root_file(import_dir + "/release.manifest", gid=0, mode=0o600,
                                     maximum=simulation.MANIFEST_LIMIT)
    receipt = reader.read_root_file(import_dir + "/d8/artifact.json", gid=0, mode=0o444,
                                    maximum=simulation.RECEIPT_LIMIT)
    complete = reader.read_root_file(import_dir + "/d8/COMPLETE", gid=0, mode=0o444,
                                     maximum=simulation.COMPLETE_BYTES)
    infra_data = reader.read_root_file(import_dir + "/compose-offline.override.yml",
                                       gid=0, mode=0o600, maximum=4096)
    upstream = upstream_override(infra_data)
    binding = simulation.validate_manifest(manifest, commit)
    require(binding["format"] == simulation.MANIFEST_V3_FORMAT, "MANIFEST_V3_REQUIRED")
    simulation.validate_build_receipt(receipt, complete, commit)
    for service, identity in binding["image_ids"].items():
        inspect_image(f"lagrange-station-{service}:{commit}", identity, commit)
    for identity in set(upstream.values()):
        inspect_image(identity, identity)
    return manifest, binding, infra_data, upstream, "sha256:" + complete.decode("ascii").strip()


